@Composable
fun AppNavHost() {
    val navController = rememberNavController()

    NavHost(navController = navController, startDestination = Pages.Start.name) {
        composable(Pages.Start.name) {
            Start(navController)
        }
        composable(Pages.State.name) {
            State(navController)
        }
    }
}






